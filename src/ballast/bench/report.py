"""Report generation: turns run records into the tables a reviewer asks for.

Every number in here is computed from `SuiteResult.rows`; nothing is hand-written,
so `docs/BENCHMARK.md` can be regenerated by CI and a stale claim becomes a diff
instead of a lie.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from typing import Any

from ..bench.stats import cohen_h, mcnemar_exact, paired_ratio_ci, pass_k_measured, wilson_interval
from .runner import SuiteResult


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _money(x: float) -> str:
    return f"{x:.4f}"


def markdown(result: SuiteResult, *, baseline: str = "naive", reference: str = "ballast") -> str:
    summary = result.arms_summary()
    arms = [a for a in summary if a in {r.arm for r in result.rows}]
    lines: list[str] = []
    lines.append(f"_generated {result.generated_at} · provider `{result.provider}` · {len(result.rows)} runs over {len(arms)} arms_")
    lines.append("")
    lines.append("## Headline")
    lines.append("")
    lines.append("| arm | success | 95% CI | mean cost | mean prompt tok | peak ctx | calls | offloads | compactions | guardrails |")
    lines.append("|---|---:|---|---:|---:|---:|---:|---:|---:|---:|")
    for arm_name in _ordered(arms, reference):
        s = summary[arm_name]
        n = s["runs"]
        k = int(round(s["success_rate"] * n))
        low, high = wilson_interval(k, n)
        lines.append(
            f"| `{arm_name}` | {_pct(s['success_rate'])} ({k}/{n}) | [{_pct(low)}, {_pct(high)}] | "
            f"{_money(s['mean_cost'])} | {s['mean_prompt_tokens']:.0f} | {s['peak_prompt_tokens']:.0f} | "
            f"{s['mean_calls']:.1f} | {s['offloads']} | {s['compactions']} | {s['guardrail_blocks']} |"
        )
    lines.append("")

    lines.append("## Reliability (pass^k on repeat draws)")
    lines.append("")
    ks = (1, 2, 3)
    lines.append("| arm | " + " | ".join(f"measured pass^{k}" for k in ks) + " | i.i.d. pass^3 |")
    lines.append("|---|---:|---:|---:|---:|")
    reps = 1
    for arm_name in _ordered(arms, reference):
        per_task: dict[str, list[bool]] = defaultdict(list)
        for row in result.rows:
            if row.arm == arm_name:
                per_task[row.scenario_id].append(bool(row.ok))
        draws = list(per_task.values())
        reps = max((len(d) for d in draws), default=1)
        measured = [pass_k_measured(draws, k) for k in ks]
        rate = sum(sum(d) / len(d) for d in draws) / len(draws) if draws else 0.0
        lines.append(
            f"| `{arm_name}` | " + " | ".join(_pct(m) for m in measured) + f" | {_pct(rate ** 3)} |"
        )
    lines.append("")
    lines.append(
        "_**measured** is the share of tasks passing every one of their first k draws; **i.i.d.** is "
        "the tau-bench estimate `p̂^k` that assumes draws are independent. Under this repo's offline "
        "surrogate the two columns disagree on purpose: the policy is deterministic, so each task's "
        "draws are identical and measured pass^k equals pass^1 exactly. The decay in the last column "
        "is a model of a stochastic agent, not a measurement of this one — it becomes real data only "
        "against a provider at temperature > 0._"
    )
    if reps < 2:
        lines.append("")
        lines.append("_reps < 2 in this run: nothing is measurable beyond pass^1; use `--reps 3`._")
    lines.append("")

    lines.append("## Cost / quality frontier")
    lines.append("")
    lines.append("| arm | mean cost | success | dominates |")
    lines.append("|---|---:|---:|---|")
    frontier = _pareto(arms, summary)
    for arm_name in _ordered(arms, reference):
        s = summary[arm_name]
        dom = ", ".join(f"`{o}`" for o in frontier.get(arm_name, [])) or "—"
        lines.append(f"| `{arm_name}` | {_money(s['mean_cost'])} | {_pct(s['success_rate'])} | {dom} |")
    lines.append("")

    lines.append("## Paired comparisons vs reference arm")
    lines.append("")
    if reference in arms:
        lines.append(f"Paired on identical scenarios against `{reference}` (McNemar exact on discordant pairs):")
        lines.append("")
        lines.append("| comparison | Δ success | discordant b/c | p (exact) | effect h | cost ratio [95% CI] |")
        lines.append("|---|---:|---|---:|---:|---|")
        for arm_name in _ordered(arms, reference):
            if arm_name == reference:
                continue
            cmp_ = _paired(result, arm_name, reference)
            lines.append(
                f"| `{arm_name}` vs `{reference}` | {cmp_['delta']:+.3f} | {cmp_['b']}/{cmp_['c']} | {cmp_['p']:.4f} | "
                f"{cmp_['h']:+.2f} | {cmp_['ratio'].point:.2f} [{cmp_['ratio'].low:.2f}, {cmp_['ratio'].high:.2f}] |"
            )
    lines.append("")

    lines.append("## Where the savings actually come from")
    lines.append("")
    lines.append(f"Aggregated over every scenario, the reference arm's cost ratio can hide its own sign. "
                 "Split by scenario class (tags from `env/fixtures.py`) it usually cannot:")
    lines.append("")
    lines.append("| scenario class | n | mean cost " + reference + " | mean cost " + baseline + " | " + baseline + "/" + reference + " cost | " + baseline + "/" + reference + " prompt tokens |")
    lines.append("|---|---:|---:|---:|---|---|")
    for label, ids in _classes(result).items():
        cmp_ = _paired(result, baseline, reference, restrict=ids)
        if not ids:
            continue
        cost_ref = sum(r.cost for r in result.rows if r.arm == reference and r.scenario_id in ids) / max(1, len([r for r in result.rows if r.arm == reference and r.scenario_id in ids]))
        cost_base = sum(r.cost for r in result.rows if r.arm == baseline and r.scenario_id in ids) / max(1, len([r for r in result.rows if r.arm == baseline and r.scenario_id in ids]))
        ratio = cmp_["ratio"]
        tok = _paired_tokens(result, baseline, reference, ids)
        enough = len(ids) >= 5
        cost_cell = f"{ratio.point:.2f} [{ratio.low:.2f}, {ratio.high:.2f}]" if ratio and enough else (f"{ratio.point:.2f} (n too small)" if ratio else "—")
        tok_cell = f"{tok.point:.2f} [{tok.low:.2f}, {tok.high:.2f}]" if tok and enough else (f"{tok.point:.2f} (n too small)" if tok else "—")
        lines.append(f"| {label} | {len(ids)} | {_money(cost_ref)} | {_money(cost_base)} | {cost_cell} | {tok_cell} |")
    lines.append("")
    lines.append("_A ratio above 1.00 with a lower bound above 1.00 means the uncontrolled arm is "
                 "**reliably more expensive** on that class; a CI spanning 1.00 means the suite cannot "
                 "tell. Read the classes, not just the aggregate._")
    lines.append("")

    lines.append("## The crossover")
    lines.append("")
    crossover = _crossover(result, baseline, reference)
    if crossover:
        lines.append(f"Sorted by task length, the ratio of `{baseline}` to `{reference}` prompt tokens is not a "
                     "constant — it is a curve that crosses 1.00. This is the part a single aggregate number erases.")
        lines.append("")
        lines.append(f"| task | length ({baseline} prompt tok) | {baseline}/{reference} tokens | {baseline}/{reference} cost |")
        lines.append("|---|---:|---:|---:|")
        crossing = next((i for i, row in enumerate(crossover) if row[2] >= 1.0), None)
        for index, (sid, length, tok_ratio, cost_ratio) in enumerate(crossover):
            flag = " ← first task where control pays" if index == crossing else ""
            lines.append(f"| `{sid}` | {length:,.0f} | {tok_ratio:.2f} | {cost_ratio:.2f}{flag} |")
        lines.append("")
        lines.append("_Below 1.00 the controlled arm is the more expensive one; above it, cheaper. "
                     "The overhead is the retrieved policy briefing and skill machinery; the payoff is "
                     "that a folded transcript is billed on every later call instead of forever._")
    lines.append("")

    lines.append("## Where failures come from")
    lines.append("")
    lines.append("| arm | agent faults | runtime faults | environment faults | top codes |")
    lines.append("|---|---:|---:|---:|---|")
    for arm_name in _ordered(arms, reference):
        owners: Counter[str] = Counter()
        codes: Counter[str] = Counter()
        for row in result.rows:
            if row.arm != arm_name:
                continue
            owners.update(row.faults.get("by_owner") or {})
            codes.update(row.faults.get("by_code") or {})
        top = ", ".join(f"{c}×{n}" for c, n in codes.most_common(3)) or "—"
        lines.append(f"| `{arm_name}` | {owners.get('agent', 0)} | {owners.get('runtime', 0)} | {owners.get('environment', 0)} | {top} |")
    lines.append("")

    lines.append("## Per-scenario outcome")
    lines.append("")
    scenario_ids = sorted({r.scenario_id for r in result.rows})
    lines.append("| scenario | " + " | ".join(f"`{a}`" for a in _ordered(arms, reference)) + " |")
    lines.append("|---" * (len(arms) + 1) + "|")
    index = {(r.arm, r.scenario_id): r for r in result.rows}
    for sid in scenario_ids:
        cells = []
        for arm_name in _ordered(arms, reference):
            row = index.get((arm_name, sid))
            cells.append("✅" if row and row.ok else ("❌" if row else "·"))
        lines.append(f"| {sid} | " + " | ".join(cells) + " |")
    lines.append("")
    return "\n".join(lines)


def _ordered(arms: list[str], reference: str) -> list[str]:
    priority = {"naive": 0, "ballast": 1}
    return sorted(arms, key=lambda a: (priority.get(a, 2), a))


def _pareto(arms: list[str], summary: dict[str, dict[str, Any]]) -> dict[str, list[str]]:
    """Which arms does each arm strictly dominate (cheaper *and* at least as good)?"""
    out: dict[str, list[str]] = {}
    for a in arms:
        wins = []
        for b in arms:
            if a == b:
                continue
            sa, sb = summary[a], summary[b]
            if sa["success_rate"] >= sb["success_rate"] and sa["mean_cost"] <= sb["mean_cost"] and (
                sa["success_rate"] > sb["success_rate"] or sa["mean_cost"] < sb["mean_cost"]
            ):
                wins.append(b)
        out[a] = wins
    return out


def _crossover(result: SuiteResult, baseline: str, reference: str, *, min_tasks: int = 4) -> list[tuple[str, float, float, float]]:
    """Longest-first ratio of the uncontrolled arm to the controlled arm.

    Only meaningful for tasks long enough to overflow a window, so the set is chosen by
    measured size rather than by a hand-maintained tag list.
    """
    ids = {r.scenario_id for r in result.rows}
    pairs = []
    for sid in ids:
        base = [r for r in result.rows if r.arm == baseline and r.scenario_id == sid]
        ref = [r for r in result.rows if r.arm == reference and r.scenario_id == sid]
        if not base or not ref:
            continue
        b_tok = sum(r.prompt_tokens_total for r in base) / len(base)
        r_tok = sum(r.prompt_tokens_total for r in ref) / len(ref)
        if r_tok <= 0:
            continue
        b_cost = sum(r.cost for r in base) / len(base)
        r_cost = sum(r.cost for r in ref) / len(ref)
        pairs.append((sid, b_tok, b_tok / r_tok, (b_cost / r_cost) if r_cost else float("inf")))
    long_tasks = [p for p in pairs if p[1] >= 50_000]
    if len(long_tasks) < min_tasks:
        return []
    return sorted(long_tasks, key=lambda p: p[1])


def _classes(result: SuiteResult) -> dict[str, set[str]]:
    """Scenario ids by declared class, so cost claims can be split by task type."""
    from ..env.fixtures import scenarios

    classes: dict[str, set[str]] = {"all scenarios": {r.scenario_id for r in result.rows}}
    named = {s.id: s for s in scenarios()}
    for tag in ("long_horizon", "batch", "bloat", "restraint", "flaky", "retrieval"):
        ids = {sid for sid, sc in named.items() if tag in sc.tags and sid in classes["all scenarios"]}
        if ids:
            classes[f"class: {tag}"] = ids
    ordinary = {r.scenario_id for r in result.rows} - set().union(*(v for k, v in classes.items() if k.startswith("class:")) if any(k.startswith("class:") for k in classes) else [set()])
    if ordinary:
        classes["ordinary (no special tag)"] = ordinary
    return classes


def _paired_tokens(result: SuiteResult, left: str, right: str, ids: set[str]) -> Any:
    def best(arm: str) -> dict[str, int]:
        out: dict[str, list[int]] = {}
        for row in result.rows:
            if row.arm == arm and row.scenario_id in ids:
                out.setdefault(row.scenario_id, []).append(row.prompt_tokens_total)
        return {k: sum(v) / len(v) for k, v in out.items()}

    l, r = best(left), best(right)
    shared = sorted(set(l) & set(r))
    if not shared:
        return None
    return paired_ratio_ci([r[s] for s in shared], [l[s] for s in shared])


def _paired(result: SuiteResult, left: str, right: str, restrict: set[str] | None = None) -> dict[str, Any]:
    def best(arm: str) -> dict[str, tuple[bool, float]]:
        out: dict[str, tuple[bool, float]] = {}
        for row in result.rows:
            if row.arm != arm or (restrict is not None and row.scenario_id not in restrict):
                continue
            prev = out.get(row.scenario_id)
            out[row.scenario_id] = (row.ok, row.cost) if prev is None or row.ok else prev
        return out

    l, r = best(left), best(right)
    shared = sorted(set(l) & set(r))
    pairs = [(int(r[s][0]), int(l[s][0])) for s in shared]
    p, b, c = mcnemar_exact(pairs)
    rate_l = sum(v[0] for v in l.values() if v[0]) / max(1, len(l))
    rate_r = sum(v[0] for v in r.values() if v[0]) / max(1, len(r))
    costs_l = [l[s][1] for s in shared]
    costs_r = [r[s][1] for s in shared]
    ratio = paired_ratio_ci(costs_r, costs_l) if costs_l else None
    return {
        "delta": rate_l - rate_r,
        "p": p,
        "b": b,
        "c": c,
        "h": cohen_h(rate_r, rate_l),
        "ratio": ratio,
        "n": len(shared),
    }


def summary_json(result: SuiteResult) -> dict[str, Any]:
    return {"provider": result.provider, "model": result.model, "reps": result.reps, "summary": result.arms_summary()}
